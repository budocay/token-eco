/**
 * Offline multi-language benchmark. Ground truth: universal-ctags (brew install universal-ctags).
 * Corpus: repositories cloned into /tmp/te-corpus (see CORPUS below).
 * Usage: node bench/languages.ts [go,rust,…]   → bench/LANGUAGES.md
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { outline } from "../src/tools/outline.ts";
import { readSymbol } from "../src/tools/readSymbol.ts";
import { estimateTokens } from "../src/tokens.ts";
import { nativeReadChars, splitLines } from "../src/types.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = "/tmp/te-corpus";
const CTAGS = existsSync("/opt/homebrew/bin/ctags") ? "/opt/homebrew/bin/ctags" : "ctags";

const CORPUS: Record<string, [string, string[]]> = {
  go: ["gin", [".go"]], rust: ["ripgrep/crates", [".rs"]], java: ["gson/gson/src/main", [".java"]],
  kotlin: ["okio/okio/src", [".kt"]], c: ["jq/src", [".c", ".h"]], cpp: ["fmt", [".h", ".cc"]],
  csharp: ["MediatR/src", [".cs"]], swift: ["Alamofire/Source", [".swift"]], php: ["Slim/Slim", [".php"]],
  ruby: ["sinatra/lib", [".rb"]], lua: ["Penlight/lua", [".lua"]], elixir: ["plug/lib", [".ex"]],
  scala: ["os-lib/os/src", [".scala"]], dart: ["args/lib", [".dart"]], shell: ["nvm", [".sh"]],
};
/** ctags kinds considered “structural” (the ones an outline must show). */
const STRUCTURAL = new Set(["function", "method", "class", "struct", "interface", "enum", "trait", "module", "namespace",
  "type", "typedef", "protocol", "extension", "implementation", "constructor", "singletonMethod", "union", "record",
  "object", "func", "subroutine", "macro", "impl", "delegate", "mixin", "fun", "package"]);
/** Ignored tags: anonymous symbols and lambdas generated by ctags. */
const anonymous = (t: Tag) => /^(<|__anon)/.test(t.name);

interface Tag { name: string; line: number; end?: number; kind: string; path: string }

function listAll(d: string, ext: string[], max = 50): string[] {
  const out: string[] = [];
  const walk = (x: string) => {
    for (const e of readdirSync(x, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      if (out.length >= max) return;
      const p = join(x, e.name);
      if (e.isDirectory() && !/^(\.|node_modules|vendor|test|tests|spec|examples?|third_party)/.test(e.name)) walk(p);
      else if (e.isFile() && ext.some((x) => e.name.endsWith(x)) && statSync(p).size > 1000) out.push(p);
    }
  };
  walk(d);
  return out;
}

function tags(files: string[]): Map<string, Tag[]> {
  const output = execFileSync(CTAGS, ["--output-format=json", "--fields=+neK", "--extras=-F", "-f", "-", ...files],
    { maxBuffer: 1 << 28 }).toString();
  const byFile = new Map<string, Tag[]>();
  for (const l of output.split("\n")) {
    if (!l.startsWith("{")) continue;
    const t = JSON.parse(l);
    if (t._type !== "tag") continue;
    (byFile.get(t.path) ?? byFile.set(t.path, []).get(t.path)!).push(t);
  }
  return byFile;
}

const pc = (a: number, b: number) => (b ? (100 * a / b).toFixed(1) + " %" : "–");
const choice = process.argv[2]?.split(",");
const reportLines: string[] = [];
const failures: string[] = [];
let tot = { decls: 0, seen: 0, symT: 0, symOk: 0 };

for (const [lang, [folder, ext]] of Object.entries(CORPUS)) {
  if (choice && !choice.includes(lang)) continue;
  const filePath = join(ROOT, folder);
  if (!existsSync(filePath)) { console.error(`corpus absent : ${filePath}`); continue; }
  const files = listAll(filePath, ext);
  const allItems = tags(files);
  let decls = 0, seen = 0, linesOut = 0, legit = 0, tokOut = 0, tokNat = 0, symT = 0, symOk = 0, symStart = 0, tokSym = 0, tokSymNat = 0;
  const langFailures: string[] = [];
  let worst = { n: 0, f: "", ex: "" };

  for (const f of files) {
    const t = allItems.get(f) ?? [];
    const lines = splitLines(readFileSync(f, "utf8"));
    const native = estimateTokens(nativeReadChars(lines));
    const ap = await outline({ file: f });
    const seenF = new Set([...ap.text.matchAll(/^\s*(\d+)\|/gm)].map((m) => Number(m[1])));
    // Capped outline (huge files): only the displayed part is judged.
    const maxCount = /\[\+\d+ declarations/.test(ap.text) ? Math.max(...seenF) : Infinity;
    const struct = t.filter((x) => STRUCTURAL.has(x.kind) && !anonymous(x) && x.line <= maxCount);
    const tagLines = new Set(t.map((x) => x.line));
    decls += struct.length;
    seen += struct.filter((x) => seenF.has(x.line)).length;
    linesOut += seenF.size;
    const noiseF = [...seenF].filter((l) => !tagLines.has(l));
    legit += seenF.size - noiseF.length;
    if (noiseF.length > worst.n) worst = { n: noiseF.length, f, ex: noiseF.slice(0, 3).map((l) => `${l}: ${lines[l - 1].trim().slice(0, 50)}`).join(" | ") };
    tokOut += estimateTokens(ap.text); tokNat += native;
    if (langFailures.length < 2) {
      const missing = struct.find((x) => !seenF.has(x.line));
      if (missing) langFailures.push(`outline ${f.replace(ROOT + "/", "")}:${missing.line} ${missing.kind} ${missing.name} — “${lines[missing.line - 1]?.trim().slice(0, 70)}”`);
    }

    const count = new Map<string, number>();
    for (const x of struct) count.set(x.name, (count.get(x.name) ?? 0) + 1);
    for (const x of struct.filter((x) => x.end && count.get(x.name) === 1).slice(0, 10)) {
      const r = await readSymbol({ file: f, name: x.name });
      const m = /\[(\d+)-(\d+)\/\d+\]/.exec(r.text.split("\n")[0]);
      const a = m ? Number(m[1]) : -1, b = m ? Number(m[2]) : -1;
      symT++; tokSym += estimateTokens(r.text); tokSymNat += native;
      const endOk = b >= x.end! && lines.slice(x.end, b).every((l) => /^\s*(#.*|\/\/.*|--.*)?$/.test(l));
      if (a <= x.line && x.line <= b) symStart++;
      if (a <= x.line && a >= x.line - 30 && endOk) symOk++;
      else if (langFailures.length < 5) langFailures.push(`lire_symbole ${f.replace(ROOT + "/", "")} › ${x.name} (${x.kind}) : expected ${x.line}-${x.end}, obtenu ${a}-${b}`);
    }
  }
  tot = { decls: tot.decls + decls, seen: tot.seen + seen, symT: tot.symT + symT, symOk: tot.symOk + symOk };
  if (!decls) { // ctags has no parser for this language
    const l = `| ${lang} | ${files.length} | no ctags truth | – | ${pc(tokOut, tokNat)} | – | – |`;
    console.log(l); reportLines.push(l); continue;
  }
  const line = `| ${lang} | ${files.length} | ${pc(seen, decls)} | ${pc(legit, linesOut)} | ${pc(tokOut, tokNat)} | ${pc(symOk, symT)} / ${pc(symStart, symT)} (${symT}) | ${pc(tokSym, tokSymNat)} |`;
  console.log(line);
  reportLines.push(line);
  failures.push(...langFailures.map((e) => `- ${lang} : ${e}`));
  if (worst.n) failures.push(`- ${lang}: max noise ${worst.n} lines in ${worst.f.replace(ROOT + "/", "")} — ${worst.ex}`);
}

const report = `# token-eco multi-language benchmark (ground truth: universal-ctags)

Corpus: open-source repositories cloned into ${ROOT} (50 files max per language). Estimated tokens (chars/4).

| Language | Files | Outline recall | Outline precision | Outline size / Read | Read symbol exact / start ok (n) | Read symbol size / Read |
|---|---|---|---|---|---|---|
${reportLines.join("\n")}

Global : recall outline ${pc(tot.seen, tot.decls)}, lire_symbole exact ${pc(tot.symOk, tot.symT)}.
“Precision” = share of outline lines that are a ctags tag (all kinds); ctags ignores some
useful declarations (e.g. constants), so this figure is a lower bound.

Failure examples:
${failures.join("\n")}
`;
writeFileSync(join(HERE, "LANGUAGES.md"), report);
console.log("\n" + failures.join("\n"));
